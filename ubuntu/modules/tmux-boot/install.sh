#!/usr/bin/env bash
# tmux-boot module installer (user level, never root). The module is a set of assets found BY GLOB next to this file, so
# a new script or unit only has to be dropped in here:
#
#   tmux-*          files without an extension (any mode: install -m 755 sets the exec bit) -> $HOME/.local/bin (tmux-boot, tmux-autosave, tmux-lib, ...)
#   tmux-*.service  systemd user units                     -> $HOME/.config/systemd/user
#   tmux-*.timer
#
# A unit with an [Install] section is enabled and, except for tmux-boot.service, also started (`enable --now`: a timer
# or a service the module ships only does its work while it runs, so an enabled-but-dead unit must show as drift).
# tmux-boot.service alone is only enabled: the tmux server that may be running now must not be touched, and the unit
# runs at the next boot. A unit without an [Install] section (the oneshot service a timer fires) is only copied.
# Linger is switched on, so user units start at boot.
#
#   install.sh           install (idempotent: a second run changes nothing)
#   install.sh --plan    read-only: what install would do
#   install.sh --check   read-only: exit 0 = in place, 3 = drift, 10 = needs a manual step, anything else = broken checker
#
# Exit codes follow the ubuntu-tweak system-module protocol (0 ok, 3 drift, 10 manual, 75 transient).
#
# Failover, decided here and not by the engine's [[fallback]] (which would also fire on an unrelated failure such as a
# full disk): with no user systemd bus (an ssh session without a bus, a container) the install writes an XDG autostart
# entry instead of tmux-boot.service, and the server then starts at graphical login rather than at boot; the other
# units cannot be installed without the bus and are reported as drift. When the bus is there, the unit is the one start
# path: a stale autostart entry is drift, and install removes it.
#
# TMUX_BOOT_UNIT_DIR / TMUX_BOOT_BIN_DIR / TMUX_BOOT_AUTOSTART_DIR move the three install locations; they exist for
# the tests (a temp HOME). The unit and the autostart entry's Exec always name the script in BIN_DIR as installed.
# shellcheck disable=SC2329  # check_systemd and check_autostart are called through $check
set -u

mode=install
case "${1:-}" in
  --check) mode=check ;;
  --plan) mode=plan ;;
  "") ;;
  *) echo "usage: $0 [--plan|--check]" >&2; exit 2 ;;
esac

here=$(cd "$(dirname "$0")" && pwd -P)
bin_dir=${TMUX_BOOT_BIN_DIR:-$HOME/.local/bin}
unit_dir=${TMUX_BOOT_UNIT_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user}
autostart_dir=${TMUX_BOOT_AUTOSTART_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/autostart}
autostart_file="$autostart_dir/tmux-boot.desktop"
boot_unit=tmux-boot.service

# a unit has an [Install] section when a line of its own says so: systemd accepts it as the very first line and with
# leading or trailing blanks
has_install_section() {
  local line
  while IFS= read -r line || [ -n "$line" ]; do
    [[ $line =~ ^[[:space:]]*\[Install\][[:space:]]*$ ]] && return 0
  done < "$1"
  return 1
}

# the module's assets, by glob (names only, relative to $here). Every extension-less tmux-* file is a script whatever
# its own mode: install -m 755 sets the installed mode, so a source committed without the exec bit (tmux-lib, whose
# header says it is sourced and never run, is the natural case) must not be silently dropped. Anything else with a
# dot that is not a unit or the failover template is a naming mistake, not a silent skip: nothing would install or
# check it, so every mode below reports it.
scripts=()
units=()
unknown=()
installable=() # the units with an [Install] section: enabled (and started, except the boot unit)
for f in "$here"/tmux-*; do
  [ -f "$f" ] || continue
  name=${f##*/}
  case $name in
    *.service|*.timer)
      units+=("$name")
      has_install_section "$f" && installable+=("$name")
      ;;
    tmux-boot.desktop) ;; # the failover entry is generated by desktop_text; the module copy is only the source
    *.*) unknown+=("$name") ;; # a .path/.socket unit or a stray file: the installer knows no home for it
    *) scripts+=("$name") ;;
  esac
done

# every installable unit except the boot unit is bus-only: without the user systemd bus it has no failover at all
bus_less=()
for u in "${installable[@]}"; do [ "$u" = "$boot_unit" ] || bus_less+=("$u"); done

# The library goes first: every script sources it, so when its copy fails the scripts that are already installed must not
# have been replaced by versions that cannot load it (the loop stops at the first failure)
for i in "${!scripts[@]}"; do
  if [ "${scripts[i]}" = tmux-lib ]; then
    scripts=(tmux-lib "${scripts[@]:0:i}" "${scripts[@]:i+1}")
    break
  fi
done

# the user's systemd bus is found through XDG_RUNTIME_DIR: ssh and cron sessions do not set it, the unit still lives
uid=$(id -u)
if [ -z "${XDG_RUNTIME_DIR:-}" ] && [ -d "/run/user/$uid" ]; then export XDG_RUNTIME_DIR="/run/user/$uid"; fi

manual() { echo "needs manual: $1" >&2; exit 10; }
sc() { systemctl --user "$@"; }
same() { [ -f "$2" ] && cmp -s "$1" "$2"; }
linger_ok() { [ "$(loginctl show-user "$(id -un)" -p Linger --value 2>/dev/null)" = yes ]; }
bus_ok() { systemctl --user show-environment >/dev/null 2>&1; }
tmux_ok() { command -v tmux >/dev/null 2>&1; }
is_timer() { [[ $1 == *.timer ]]; }
script_ok() { same "$here/$1" "$bin_dir/$1" && [ -x "$bin_dir/$1" ]; }
unit_file_ok() { same "$here/$1" "$unit_dir/$1"; }
unit_enabled() { [ "$(sc is-enabled "$1" 2>/dev/null)" = enabled ]; }
# a timer, and every service except the boot unit, must also run now: only tmux-boot.service is enabled without
# starting (the running tmux server must not be touched; the unit runs at the next boot)
starts_now() { is_timer "$1" || [ "$1" != "$boot_unit" ]; }
unit_ok() { unit_enabled "$1" && { ! starts_now "$1" || sc is-active --quiet "$1"; }; }
enable_cmd() { if starts_now "$1"; then echo "systemctl --user enable --now $1"; else echo "systemctl --user enable $1"; fi; }
# the autostart entry is generated: its Exec is the absolute path of the installed script
desktop_text() {
  local line
  while IFS= read -r line; do printf '%s\n' "${line//@BIN@/"$bin_dir/tmux-boot"}"; done < "$here/tmux-boot.desktop"
}
autostart_ok() { [ -f "$autostart_file" ] && [ "$(desktop_text)" = "$(cat "$autostart_file")" ]; }

check_systemd() { # prints one line per unmet fact
  local u
  for u in "${units[@]}"; do unit_file_ok "$u" || echo "$unit_dir/$u is missing or differs from the module copy"; done
  for u in "${installable[@]}"; do
    unit_ok "$u" && continue
    if starts_now "$u"; then echo "$u is not enabled and running ($(enable_cmd "$u")), so what it runs never runs"
    else echo "$u is not enabled ($(enable_cmd "$u"))"; fi
  done
  linger_ok || echo "systemd linger is off for $(id -un), so the units start at login, not at boot (loginctl enable-linger)"
  [ ! -e "$autostart_file" ] || echo "$autostart_file is stale: the unit is the start path while the user bus is available (install removes it)"
}
check_autostart() {
  local u
  autostart_ok || echo "no user systemd bus: $autostart_file is the start path and it is missing or differs"
  for u in "${bus_less[@]}"; do
    echo "no user systemd bus: $u cannot be installed, so what it runs never runs (run apply from a session that has the user bus)"
  done
}

if [ "$mode" = check ]; then
  problems=()
  tmux_ok || problems+=("tmux is not installed (apt: tmux, declared in packages.toml)")
  for u in "${unknown[@]}"; do
    problems+=("$here/$u is neither a script (extension-less tmux-*) nor a unit (tmux-*.service|tmux-*.timer), so it would never be installed")
  done
  for s in "${scripts[@]}"; do script_ok "$s" || problems+=("$bin_dir/$s is missing or differs from the module copy"); done
  if bus_ok; then check=check_systemd; else check=check_autostart; fi
  while IFS= read -r line; do [ -z "$line" ] || problems+=("$line"); done < <($check)
  if [ "${#problems[@]}" -gt 0 ]; then
    printf 'drift: %s\n' "${problems[@]}"
    exit 3
  fi
  exit 0
fi

if [ "$mode" = plan ]; then
  for u in "${unknown[@]}"; do echo "UNKNOWN ASSET $here/$u: neither a script (extension-less tmux-*) nor a unit (tmux-*.service|tmux-*.timer)" >&2; done
  for s in "${scripts[@]}"; do script_ok "$s" || echo "install $here/$s -> $bin_dir/$s"; done
  if bus_ok; then
    reload=0
    for u in "${units[@]}"; do unit_file_ok "$u" || { echo "install $here/$u -> $unit_dir/$u"; reload=1; }; done
    [ "$reload" = 0 ] || echo "systemctl --user daemon-reload"
    for u in "${installable[@]}"; do unit_ok "$u" || enable_cmd "$u"; done
    linger_ok || echo "loginctl enable-linger $(id -un)   (so the units start at boot, before any login)"
    [ ! -e "$autostart_file" ] || echo "remove the stale $autostart_file"
  else
    autostart_ok || echo "no user systemd bus: write the XDG autostart entry $autostart_file (the server starts at graphical login)"
    for u in "${bus_less[@]}"; do
      echo "no user systemd bus: $u cannot be installed here; it follows once apply runs where the user bus exists"
    done
  fi
  exit 0
fi

if [ "${#unknown[@]}" -gt 0 ]; then
  echo "install.sh: $here/${unknown[0]} is neither a script (extension-less tmux-*) nor a unit (tmux-*.service|tmux-*.timer), refusing to install a half module" >&2
  exit 1
fi
tmux_ok || manual "tmux is not installed; run \`ubuntu-tweak apply --commit\` (packages.toml installs it) or \`sudo apt-get install -y tmux\`"
mkdir -p "$bin_dir" || exit 1
for s in "${scripts[@]}"; do script_ok "$s" || install -m 755 "$here/$s" "$bin_dir/$s" || exit 1; done

if ! bus_ok; then
  echo "tmux-boot: no user systemd bus, installing the XDG autostart entry instead (the server starts at graphical login)"
  mkdir -p "$autostart_dir" || exit 1
  autostart_ok || desktop_text > "$autostart_file" || exit 1
  for u in "${bus_less[@]}"; do
    echo "tmux-boot: WARNING $u was NOT installed (no user systemd bus): what it runs never runs until apply runs where the user bus exists; --check reports it as drift" >&2
  done
  exit 0
fi

mkdir -p "$unit_dir" || exit 1
reload=0
for u in "${units[@]}"; do unit_file_ok "$u" || { install -m 644 "$here/$u" "$unit_dir/$u" || exit 1; reload=1; }; done
[ "$reload" = 0 ] || sc daemon-reload || exit 1
# the boot unit first, then the rest in glob order: a failing enable of an auxiliary unit must not leave the machine
# without the boot path (alphabetical order would enable tmux-autosave.timer before tmux-boot.service)
for u in "${installable[@]}"; do
  [ "$u" = "$boot_unit" ] || continue
  unit_ok "$u" || sc enable "$u" || exit 1
done
for u in "${installable[@]}"; do
  [ "$u" != "$boot_unit" ] || continue
  unit_ok "$u" || sc enable --now "$u" || exit 1
done
rm -f "$autostart_file"
# enabling does not start tmux-boot.service: the tmux server that may be running now must not be touched, and the
# script would do nothing anyway. The unit runs at the next boot.
linger_ok || loginctl enable-linger "$(id -un)" 2>/dev/null \
  || manual "systemd linger is off: run \`sudo loginctl enable-linger $(id -un)\` once so the units start at boot, then run apply again"
exit 0
