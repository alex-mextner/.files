#!/usr/bin/env bash
# dc-mcp module installer (user level, never root): the pinned binaries ~/.local/bin/mcp-auth-proxy and ~/.local/bin/cloudflared,
# ~/.config/dc-mcp.env (this machine's non-secret settings, rendered from [modules.dc-mcp]) and ~/.config/dc-mcp-auth.env
# (the proxy password, generated here once, mode 600, never printed). The three systemd user units are NOT written here: they are
# leaves of files/.config/systemd/user (linked by the engine's files phase) and read dc-mcp.env / dc-mcp-auth.env.
#
#   install.sh           install (idempotent: a second run changes nothing)
#   install.sh --plan    read-only: what install would do
#   install.sh --check   read-only: exit 0 = in place, 3 = drift, 10 = needs a manual step
#
# Exit codes follow the ubuntu-tweak system-module protocol: 0 ok, 1 failed (a checksum mismatch is a failure, never retried),
# 3 drift, 10 manual, 75 network failure (the engine retries).
# DC_MCP_PINS_FILE replaces pins.tsv; it exists for the tests (a fake release with a known digest), nothing else sets it.
set -u

mode=install
case "${1:-}" in
  --check) mode=check ;;
  --plan) mode=plan ;;
  "") ;;
  *) echo "usage: $0 [--plan|--check]" >&2; exit 2 ;;
esac

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
# shellcheck source=lib.sh
. "$here/lib.sh"
load_options

pins=${DC_MCP_PINS_FILE:-$here/pins.tsv}
bin_dir=$HOME/.local/bin
cfg_dir=${XDG_CONFIG_HOME:-$HOME/.config}
settings_file=$cfg_dir/dc-mcp.env
auth_file=$cfg_dir/dc-mcp-auth.env
machine=$(uname -m)
tools=(mcp-auth-proxy cloudflared)

manual_lines=()
[ -n "$opt_hostname" ] || manual_lines+=("set [modules.dc-mcp] hostname in machines/<host>/machine.toml (the public name of THIS machine's connector, e.g. dc-mcp.example.com; one hostname per machine)")
# npx is the proxy's stdio backend launcher; node comes from packages.toml or ~/.local/opt/node
node_path=$HOME/.local/opt/node/bin:$PATH
PATH=$node_path command -v npx >/dev/null 2>&1 || manual_lines+=("npx (node) is not installed: install node (packages.toml / ~/.local/opt/node) so the proxy can start Desktop Commander")

# pin <tool> <field>: field 2 version, 4 sha256, 5 url of the row of this machine type
pin() { awk -F'\t' -v t="$1" -v m="$machine" -v f="$2" '$1 !~ /^#/ && $1 == t && $3 == m { print $f; exit }' "$pins"; }
have_sha() { [ -f "$1" ] && sha256sum "$1" | awk '{print $1}'; }
tool_ok() { local want; want=$(pin "$1" 4); [ -n "$want" ] && [ -x "$bin_dir/$1" ] && [ "$(have_sha "$bin_dir/$1")" = "$want" ]; }

settings_text() {
  printf '%s\n' \
    "# Written by the dc-mcp module of ubuntu-tweak (apply) from [modules.dc-mcp]. Not secret; edit the options, not this file." \
    "DC_MCP_HOSTNAME=$opt_hostname" \
    "DC_MCP_TUNNEL=$opt_tunnel" \
    "DC_MCP_PORT=$opt_port" \
    "DC_MCP_SHIM_PORT=$opt_shim_port" \
    "DC_MCP_LOG_MAX_KIB=$opt_log_max_kib" \
    "DC_MCP_LOG_KEEP=$opt_log_keep" \
    "DC_MCP_TOOL_LOG_KEEP=$opt_tool_log_keep" \
    "DC_MCP_TOOL_LOG_MAX_AGE_DAYS=$opt_tool_log_max_age_days" \
    "DC_MCP_PACKAGE=$opt_package"
}
settings_ok() { [ -n "$opt_hostname" ] && [ -f "$settings_file" ] && [ "$(settings_text)" = "$(cat "$settings_file")" ]; }
auth_has_password() { [ -f "$auth_file" ] && grep -q '^PASSWORD=.' "$auth_file"; }
auth_mode_ok() { [ "$(stat -c %a "$auth_file" 2>/dev/null)" = 600 ]; }

if [ -z "$machine" ] || [ -z "$(pin mcp-auth-proxy 4)" ]; then
  echo "needs manual: no pinned binaries for machine type $machine (pins.tsv has x86_64 and aarch64)" >&2
  exit 10
fi

if [ "$mode" = check ]; then
  problems=()
  for t in "${tools[@]}"; do tool_ok "$t" || problems+=("$bin_dir/$t is missing or is not the pinned $(pin "$t" 2) (sha256 $(pin "$t" 4))"); done
  [ -z "$opt_hostname" ] || settings_ok || problems+=("$settings_file is missing or differs from the options of [modules.dc-mcp]")
  auth_has_password || problems+=("$auth_file has no PASSWORD (generated by install, mode 600)")
  if [ -f "$auth_file" ] && ! auth_mode_ok; then problems+=("$auth_file is not mode 600"); fi
  if [ "${#problems[@]}" -gt 0 ]; then printf 'drift: %s\n' "${problems[@]}"; exit 3; fi
  if [ "${#manual_lines[@]}" -gt 0 ]; then printf 'needs manual: %s\n' "${manual_lines[@]}"; exit 10; fi
  exit 0
fi

if [ "$mode" = plan ]; then
  for t in "${tools[@]}"; do tool_ok "$t" || echo "download $(pin "$t" 5), verify sha256 $(pin "$t" 4), install -> $bin_dir/$t"; done
  [ -z "$opt_hostname" ] || settings_ok || echo "write $settings_file (hostname $opt_hostname, tunnel $opt_tunnel, ports $opt_port and $opt_shim_port)"
  auth_has_password || echo "generate a random password into $auth_file (mode 600, never printed)"
  if [ -f "$auth_file" ] && ! auth_mode_ok; then echo "chmod 600 $auth_file"; fi
  for line in "${manual_lines[@]+"${manual_lines[@]}"}"; do echo "needs manual: $line"; done
  exit 0
fi

# --- install ---------------------------------------------------------------------------------------------------------
mkdir -p "$bin_dir" "$cfg_dir" || exit 1

fetch_tool() { # download to a temp file next to the target, verify the pinned digest, rename into place
  local t=$1 url want tmp got
  url=$(pin "$t" 5); want=$(pin "$t" 4)
  tmp=$(mktemp "$bin_dir/.$t.XXXXXX") || return 1
  echo "dc-mcp: downloading $t $(pin "$t" 2) ($url)"
  if ! curl -fsSL --retry 3 --retry-delay 2 -o "$tmp" "$url"; then rm -f "$tmp"; echo "dc-mcp: cannot download $url" >&2; return 75; fi
  got=$(sha256sum "$tmp" | awk '{print $1}')
  if [ "$got" != "$want" ]; then
    rm -f "$tmp"
    echo "dc-mcp: refusing $t: sha256 of the download is $got, the pinned value is $want" >&2
    return 1
  fi
  chmod 755 "$tmp" && mv -f "$tmp" "$bin_dir/$t"
}
for t in "${tools[@]}"; do
  tool_ok "$t" && continue
  fetch_tool "$t"; rc=$?
  [ "$rc" -eq 0 ] || exit "$rc"
done

if [ -n "$opt_hostname" ] && ! settings_ok; then
  tmp=$(mktemp "$cfg_dir/.dc-mcp.env.XXXXXX") || exit 1
  settings_text > "$tmp" && chmod 644 "$tmp" && mv -f "$tmp" "$settings_file" || { rm -f "$tmp"; exit 1; }
fi

if ! auth_has_password; then
  pw=$(LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 32)
  [ "${#pw}" -eq 32 ] || { echo "dc-mcp: could not generate a password" >&2; exit 1; }
  ( umask 077; printf 'PASSWORD=%s\n' "$pw" >> "$auth_file" ) || exit 1
  unset pw
  echo "dc-mcp: generated the proxy password in $auth_file (mode 600; not printed)"
fi
if [ -f "$auth_file" ] && ! auth_mode_ok; then chmod 600 "$auth_file" || exit 1; fi

if [ "${#manual_lines[@]}" -gt 0 ]; then
  printf 'needs manual: %s\n' "${manual_lines[@]}" >&2
  exit 10
fi
exit 0
