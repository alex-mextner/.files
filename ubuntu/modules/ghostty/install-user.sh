#!/bin/sh
# Root-free Ghostty: the Ubuntu archive's `ghostty` and `libgtk4-layer-shell0` debs extracted under
# $GHOSTTY_PREFIX (default ~/.local/opt/ghostty), a ~/.local/bin/ghostty wrapper that puts the extracted
# library on LD_LIBRARY_PATH, and a desktop entry. `apt-get download` needs no root.
#
# This is the module's [[fallback]] for `apt-get install ghostty` (install.sh) when root is not available,
# and also its checker: a Ghostty from the system package counts as installed.
#
#   install-user.sh           download + extract + wrapper + desktop entry (idempotent)
#   install-user.sh --plan    read-only: the steps
#   install-user.sh --check   read-only: exit 0 = a usable Ghostty exists, 3 = drift
#
# Needs: apt-get, dpkg-deb, and libadwaita-1-0 / libgtk-4-1 (a stock Ubuntu desktop has them).
set -eu

PREFIX=${GHOSTTY_PREFIX:-$HOME/.local/opt/ghostty}
BIN=${GHOSTTY_BIN_DIR:-$HOME/.local/bin}
APPS=${XDG_DATA_HOME:-$HOME/.local/share}/applications
WRAPPER=$BIN/ghostty
ENTRY=$APPS/com.mitchellh.ghostty.desktop
# the multiarch dir that holds the extracted layer-shell library (x86_64-linux-gnu, aarch64-linux-gnu, ...); evaluated
# lazily because it only exists after the extraction. Falls back to this machine's triplet.
libdir() {
    for d in "$PREFIX"/usr/lib/*-linux-gnu; do
        if [ -e "$d/libgtk4-layer-shell.so.0" ]; then echo "$d"; return; fi
    done
    echo "$PREFIX/usr/lib/$(uname -m)-linux-gnu"
}

wrapper_text() {
    cat <<EOF
#!/bin/sh
# Generated by the ghostty module (install-user.sh): Ghostty extracted from the Ubuntu archive deb.
LD_LIBRARY_PATH="$(libdir)\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export LD_LIBRARY_PATH
exec "$PREFIX/usr/bin/ghostty" "\$@"
EOF
}

entry_text() {
    cat <<EOF
[Desktop Entry]
Name=Ghostty
Comment=Fast, feature-rich terminal emulator
Exec=$WRAPPER
Icon=com.mitchellh.ghostty
Terminal=false
Type=Application
Categories=System;TerminalEmulator;
StartupNotify=true
StartupWMClass=com.mitchellh.ghostty
X-TerminalArgExec=-e
X-TerminalArgTitle=--title
EOF
}

same() { [ -f "$1" ] && [ "$(cat "$1")" = "$2" ]; }

system_ghostty() {
    for d in ${GHOSTTY_SYSTEM_DIRS:-/usr/bin /usr/local/bin /snap/bin}; do [ -x "$d/ghostty" ] && return 0; done
    return 1
}

check() { # prints one line per problem; returns 0 ok, 3 drift
    if system_ghostty; then echo "ok: system ghostty"; return 0; fi
    bad=0
    [ -x "$PREFIX/usr/bin/ghostty" ] || { echo "MISSING: $PREFIX/usr/bin/ghostty"; bad=1; }
    [ -e "$(libdir)/libgtk4-layer-shell.so.0" ] || { echo "MISSING: $(libdir)/libgtk4-layer-shell.so.0"; bad=1; }
    # a library the extracted binary needs and the host lacks: the wrapper would fail at launch, so it is not "installed"
    if [ -x "$PREFIX/usr/bin/ghostty" ] && command -v ldd >/dev/null 2>&1; then
        missing=$(LD_LIBRARY_PATH="$(libdir)" ldd "$PREFIX/usr/bin/ghostty" 2>/dev/null | grep 'not found' || true)
        [ -z "$missing" ] || { echo "MISSING: shared libraries for $PREFIX/usr/bin/ghostty: $missing"; bad=1; }
    fi
    same "$WRAPPER" "$(wrapper_text)" || { echo "MISSING: $WRAPPER"; bad=1; }
    same "$ENTRY" "$(entry_text)" || { echo "MISSING: $ENTRY"; bad=1; }
    [ "$bad" = 0 ] && { echo "ok: user-level Ghostty at $PREFIX"; return 0; }
    return 3
}

case "${1:-}" in
--check) check; exit $? ;;
--plan)
    if check >/dev/null 2>&1; then echo "nothing to do"; exit 0; fi
    echo "apt-get download ghostty libgtk4-layer-shell0   (no root)"
    echo "extract to $PREFIX; write $WRAPPER and $ENTRY"
    exit 0 ;;
"") ;;
*) echo "usage: install-user.sh [--check|--plan]" >&2; exit 2 ;;
esac

if check >/dev/null 2>&1; then echo "ghostty already installed"; exit 0; fi

command -v apt-get >/dev/null || { echo "install-user.sh: apt-get not found" >&2; exit 1; }
command -v dpkg-deb >/dev/null || { echo "install-user.sh: dpkg-deb not found" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT INT TERM
if ! ( cd "$tmp" && apt-get download ghostty libgtk4-layer-shell0 ) >"$tmp/apt.log" 2>&1; then
    cat "$tmp/apt.log" >&2
    # exit 75 (EX_TEMPFAIL) = the engine retries with backoff, for resolver / connection causes only. A 404 (the lists name a
    # version the mirror dropped: only `apt update`, i.e. root, fixes that), no universe, an unknown package: final.
    if grep -qiE '404|not found' "$tmp/apt.log"; then
        echo "install-user.sh: the package lists are stale (404): run \`sudo apt update\`" >&2
        exit 1
    fi
    if grep -qiE 'could not resolve|temporary failure|connection failed|timed out|connection (reset|refused)|could not get lock' "$tmp/apt.log"; then exit 75; fi
    echo "install-user.sh: apt-get download failed (package lists without universe?)" >&2
    exit 1
fi
stage=$tmp/stage
mkdir -p "$stage"
for deb in "$tmp"/*.deb; do dpkg-deb -x "$deb" "$stage"; done
[ -x "$stage/usr/bin/ghostty" ] || { echo "install-user.sh: the deb has no usr/bin/ghostty" >&2; exit 1; }
# Start the NEW binary before it replaces anything: a deb that does not run on this host must not destroy a working copy.
stage_lib=""
for d in "$stage"/usr/lib/*-linux-gnu; do [ -e "$d/libgtk4-layer-shell.so.0" ] && stage_lib=$d; done
version=$(LD_LIBRARY_PATH="$stage_lib" "$stage/usr/bin/ghostty" --version 2>&1) || {
    echo "install-user.sh: the downloaded Ghostty does not start on this host, nothing was replaced: $version" >&2
    exit 1
}
# Swap the tree in as one step so a failed run never leaves a half-extracted prefix.
mkdir -p "$(dirname "$PREFIX")" "$BIN" "$APPS"
rm -rf "$PREFIX.new" "$PREFIX.old"
mv "$stage" "$PREFIX.new"
[ -e "$PREFIX" ] && mv "$PREFIX" "$PREFIX.old"
mv "$PREFIX.new" "$PREFIX"
rm -rf "$PREFIX.old"
wrapper_text > "$WRAPPER.tmp"
chmod 755 "$WRAPPER.tmp"
mv "$WRAPPER.tmp" "$WRAPPER"
entry_text > "$ENTRY.tmp"
mv "$ENTRY.tmp" "$ENTRY"
echo "installed: $(printf '%s\n' "$version" | sed -n 1p)"
check
