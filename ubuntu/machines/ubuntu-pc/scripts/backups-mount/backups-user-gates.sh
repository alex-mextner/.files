#!/usr/bin/env bash
# backups-user-gates: keep user services out of the EMPTY mountpoint directories when the backups disk is missing,
# and start them once the disk is back (rig-cli ticket 858; companion of harden-backups-mount.sh, which is the root half).
#
# Why: xp, work, .npm and friends were bind mounts of a USB disk (and are again whenever fstab binds them). With the disk
# absent at boot the mountpoints are empty SSD directories, and a service started there works on the wrong place silently.
# Each unit that lives in or uses such a tree gets a drop-in with ConditionPathIsMountPoint=: systemd then SKIPS the
# start (journal: "skipped, unmet condition check") instead of running in the empty dir. A skipped start is silent and
# is never retried by Restart=, so `retry` (run by backups-mount-retry.timer, and kicked at once by the root-side
# udev attach service on a late plug-in) finds the skipped units and starts them when their mounts are back.
#
# Drop-ins only: no unit file is edited (many belong to repos or are generated by tools). Conditions are evaluated
# at start time, so a unit that runs now is unaffected by installing them.
#
# A tree is gated only while /etc/fstab still has an ACTIVE bind line for it. move-from-backups.sh comments those lines
# out when it brings a tree back to the SSD, and a plain directory is never a mount point: a gate on it would skip the
# unit on every start. So `install` gates only the trees fstab still binds, removes the gate of a unit whose trees are
# all plain directories again, and enables the retry timer only while at least one gate is left.
#
#   backups-user-gates install [--dry-run]   write drop-ins (still-bound trees only; stale ones removed) + retry
#                                            service/timer, copy this script to ~/.local/bin, daemon-reload, enable the
#                                            timer while a gate exists, else disable it (idempotent; differing files are backed up)
#   backups-user-gates revert  [--dry-run]   remove exactly what install wrote (drop-ins, retry units, installed copy)
#   backups-user-gates retry   [--dry-run]   start gated units that were skipped for a missing mount, and docker
#                                            containers that failed to start for the same reason, once mounts are back
#   backups-user-gates list                  gated units, their mounts, and whether each mount is up
#   backups-user-gates selftest              prove the skip -> retry loop on a throw-away unit and the fstab filter on a
#                                            throw-away fstab (no real mount, fstab or unit touched)
set -euo pipefail

MARKER="backups-mount-gate"
# A dedicated file name: a drop-in called mounts.conf may already hold someone else's policy for the same unit and
# must be neither overwritten nor deleted by revert. LEGACY is the name the first version of this script wrote.
DROPIN="backups-mount-gate.conf"
LEGACY_DROPIN="mounts.conf"
UNIT_DIR="${BACKUPS_GATES_UNIT_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user}"
BIN_DIR="$HOME/.local/bin"
INSTALLED="$BIN_DIR/backups-user-gates"
STATE_DIR="${XDG_RUNTIME_DIR:-/tmp}"
TS=$(date +%Y%m%dT%H%M%S)
DRY=0
# the fstab whose active bind lines decide which trees are gated (the selftest points it at a throw-away file)
FSTAB="${BACKUPS_GATES_FSTAB:-/etc/fstab}"

# unit -> trees it needs IF they are bind mounts (relative to $HOME). Found by reading every user unit, its drop-ins and
# the scripts it execs (resolving ~/.local/bin symlinks into xp): WorkingDirectory/ExecStart/Environment under a tree.
# A template (name@.service) covers every instance. tmux-boot needs both trees: it restores panes into xp and work.
# This is only the unit -> tree map: whether a tree is gated right now is decided by active_trees (fstab), so the map
# stays right when a tree is moved to the SSD (move-from-backups.sh) or back to the disk (move-to-backups.sh).
GATES=(
  "3d-printer-vision@.service xp"
  "3d-printer-watch@.service xp"
  "agent-tv-backend.service xp"
  "agenttools-harness-dashboard.service .npm"
  "agenttools-hsw-editor-hsw-editor.service xp"
  "ai.hyperide.model-freshness.service xp"
  "aisis-dashboard.service xp"
  "autoheal.service xp"
  "conloca-merges-hourly.service work"
  "conloca-monitor.service work"
  "conloca-watch.service work"
  "hcb-alert-watcher.service xp"
  "hsw-heartbeat-20261021.service xp"
  "hsw-heartbeat.service xp"
  "hsw-observer-agent.service xp"
  "hsw-review.service xp"
  "snap-orca-sync.service xp"
  "tmux-boot.service xp work"
)
# gated units that `retry` never starts: on-demand workers started by a supervisor (3d-printer-ondemand@, 3d-cli ticket 747)
NO_RETRY_START="3d-printer-vision@.service 3d-printer-watch@.service"

say() { printf '%s\n' "$*"; }
# run a mutation, or only print it under --dry-run
do_it() { if [ "$DRY" = 1 ]; then say "  [dry-run] $*"; else "$@"; fi; }

# write $2 to file $1 unless it already has exactly that content; back up a differing file first
put_file() {
  local path=$1 content=$2
  if [ -f "$path" ] && [ "$(cat "$path")" = "$content" ]; then say "  unchanged  $path"; return; fi
  if [ -f "$path" ]; then
    say "  backup     $path -> $path.bak-$TS"
    do_it cp -p "$path" "$path.bak-$TS"
  fi
  say "  write      $path"
  if [ "$DRY" = 0 ]; then mkdir -p "$(dirname "$path")"; printf '%s\n' "$content" > "$path"; fi
}

dropin_content() {
  local conds="" t
  for t in $1; do conds+="ConditionPathIsMountPoint=%h/$t"$'\n'; done
  cat <<EOF
# $MARKER (rig-cli ticket 858), managed by backups-user-gates: remove with \`backups-user-gates revert\`.
# Why: this unit uses a tree that is a bind mount of the backups USB disk. Without the disk that path is an empty
# directory on the SSD, and starting here would silently work in (and write to) the wrong place. The condition makes
# systemd skip the start; backups-mount-retry.timer starts the unit once the mounts are back.
[Unit]
${conds%$'\n'}
EOF
}

service_unit() {
  cat <<'EOF'
# backups-mount-gate (rig-cli ticket 858): start units that were skipped for a missing backups mount.
[Unit]
Description=Start units that were skipped while the backups disk was missing

[Service]
Type=oneshot
# bounded: a hung call must not leave this unit "activating" forever (then neither the timer nor the udev kick could
# start another run); the docker calls inside have their own 8 s deadline and the docker pass ends after 200 s
TimeoutStartSec=5min
ExecStart=%h/.local/bin/backups-user-gates retry
EOF
}

timer_unit() {
  cat <<'EOF'
# backups-mount-gate (rig-cli ticket 858): a safety-net poll (about 0.5 s of CPU per run). The fast path is the
# root-side udev attach service, which also starts backups-mount-retry.service directly on a late plug-in.
[Unit]
Description=Poll for the backups disk and start skipped units

[Timer]
OnBootSec=2min
OnUnitActiveSec=2min
AccuracySec=5s

[Install]
WantedBy=timers.target
EOF
}

# the first version wrote mounts.conf; remove it only when it carries this script's marker
migrate_legacy() {
  if [ -f "$1" ] && grep -q "$MARKER" "$1"; then say "  migrate    $1 (now $DROPIN)"; do_it rm -f "$1"; fi
}

# the trees under $HOME that $FSTAB still binds, one per line, relative to $HOME: every ACTIVE (not commented out) line
# with the bind option (harden-backups-mount.sh's bind_targets uses the same option rule and also requires the source on the
# backups disk; for a gate any bind line of the tree is enough: the tree is then meant to be a mount point).
# move-from-backups.sh comments a tree's line out when it brings the tree back to the SSD, so a tree that is a plain
# directory again is not listed. fstab writes a space or tab in a path as \040 / \011, decoded like harden does (the
# same dec() awk); repeated and trailing slashes are dropped from both sides, as systemd does for a mount unit name.
# Fails when $FSTAB cannot be read or has no active line at all (an empty file): "unknown" must never look like
# "nothing is bound". A file cut short in the middle of a rewrite is not detectable here.
bound_trees() {
  [ -r "$FSTAB" ] || { echo "backups-user-gates: cannot read $FSTAB, so it is unknown which trees are bind mounts" >&2; return 1; }
  awk -v fstab="$FSTAB" 'function dec(s) { gsub(/\\040/, " ", s); gsub(/\\011/, "\t", s); return s }
    function clean(p) { gsub(/\/+/, "/", p); sub(/\/$/, "", p); return p }
    BEGIN { home = clean(ENVIRON["HOME"]) "/" }
    !/^[[:space:]]*#/ && NF>=2 { active = 1 }
    !/^[[:space:]]*#/ && NF>=4 {
      t = clean(dec($2))
      if ($4 ~ /(^|,)bind(,|$)/ && index(t, home) == 1) print substr(t, length(home) + 1)
    }
    END { if (!active) { print "backups-user-gates: " fstab " has no active line, so it is unknown which trees are bind mounts" > "/dev/stderr"; exit 3 } }' "$FSTAB"
}

# the subset of the trees in $1 (space separated) that appear in the bound_trees list $2, space separated
active_trees() {
  local t out=""
  for t in $1; do
    if grep -qxF -- "$t" <<< "$2"; then out+="$t "; fi
  done
  printf '%s' "${out% }"
}

GATED=0      # units gated by this run of install
UNGATED=()   # installed units that end this run without a gate

# remove the gate drop-ins this script wrote for unit $1 (the marker decides: someone else's file stays); $2 is the
# reason shown
remove_gate() {
  local unit=$1 f
  for f in "$UNIT_DIR/$unit.d/$DROPIN" "$UNIT_DIR/$unit.d/$LEGACY_DROPIN"; do
    if [ -f "$f" ] && grep -q "$MARKER" "$f"; then
      say "  remove     $f${2:+ ($2)}"
      do_it rm -f "$f"; do_it rmdir --ignore-fail-on-non-empty "$UNIT_DIR/$unit.d"
    fi
  done
}

# one unit's gate: written for the trees of $2 that appear in the bound_trees list $3; when none is left the unit
# joins UNGATED and a gate this script wrote is removed. Called as a plain statement: errexit stays on for the writes.
sync_gate() {
  local unit=$1 active
  active=$(active_trees "$2" "$3")
  if [ -n "$active" ]; then
    migrate_legacy "$UNIT_DIR/$unit.d/$LEGACY_DROPIN"
    put_file "$UNIT_DIR/$unit.d/$DROPIN" "$(dropin_content "$active")"
    GATED=$((GATED + 1))
    return 0
  fi
  UNGATED+=("$unit")
  say "  no gate    $unit (none of its trees [$2] is a bind mount in $FSTAB)"
  remove_gate "$unit" "stale gate"
}

# the retry timer runs only while at least one gate exists ($1 = number of gated units)
sync_retry_timer() {
  if [ "$1" -gt 0 ]; then
    do_it systemctl --user enable --now backups-mount-retry.timer
  else
    say "  no gated unit: the retry timer has nothing to start, disabled (install enables it again once a tree is bound)"
    do_it systemctl --user disable --now backups-mount-retry.timer
  fi
}

cmd_install() {
  local bound row unit trees
  # read once, before anything is changed: an unreadable fstab stops here instead of passing for "nothing is bound"
  bound=$(bound_trees) || return 1
  # `systemctl --user cat` also fails when the user manager cannot be reached; that must not read as "unit not installed"
  systemctl --user show-environment >/dev/null 2>&1 || { echo "backups-user-gates: cannot reach the user systemd (run install from the login session), nothing changed" >&2; return 1; }
  GATED=0; UNGATED=()
  say "== drop-ins in $UNIT_DIR (trees that $FSTAB still binds)"
  for row in "${GATES[@]}"; do
    unit=${row%% *}; trees=${row#* }
    if [ ! -e "$UNIT_DIR/$unit" ] && ! systemctl --user cat "$unit" >/dev/null 2>&1; then
      say "  skip       $unit (no such unit on this host)"
      continue
    fi
    sync_gate "$unit" "$trees" "$bound"
  done
  say "== retry helper, service and timer"
  if [ "$(readlink -f "$0")" != "$(readlink -f "$INSTALLED" 2>/dev/null || true)" ]; then
    if [ -f "$INSTALLED" ] && ! cmp -s "$0" "$INSTALLED"; then
      say "  backup     $INSTALLED -> $INSTALLED.bak-$TS"; do_it cp -p "$INSTALLED" "$INSTALLED.bak-$TS"
    fi
    if cmp -s "$0" "$INSTALLED" 2>/dev/null; then say "  unchanged  $INSTALLED"; else
      say "  install    $INSTALLED"; do_it install -D -m 0755 "$0" "$INSTALLED"
    fi
  fi
  put_file "$UNIT_DIR/backups-mount-retry.service" "$(service_unit)"
  put_file "$UNIT_DIR/backups-mount-retry.timer" "$(timer_unit)"
  say "== systemd --user"
  do_it systemctl --user daemon-reload
  sync_retry_timer "$GATED"
  # a start that a stale gate skipped is not retried by anything once the gate is gone and the timer is off: start such
  # units now. Every installed unit without a gate is checked, not only those whose gate this run removed, so a run
  # that was interrupted after removing gates is finished by the next one.
  for unit in "${UNGATED[@]}"; do start_skipped "$unit" "no gate any more"; done
}

cmd_revert() {
  local row f
  say "== removing drop-ins written by install"
  for row in "${GATES[@]}"; do remove_gate "${row%% *}"; done
  say "== removing retry timer/service/helper"
  do_it systemctl --user disable --now backups-mount-retry.timer || true
  for f in "$UNIT_DIR/backups-mount-retry.service" "$UNIT_DIR/backups-mount-retry.timer" "$INSTALLED"; do
    if [ -f "$f" ]; then say "  remove     $f"; do_it rm -f "$f"; fi
  done
  do_it systemctl --user daemon-reload
}

# gated drop-ins: prints "<unit>\t<mount path>[ <mount path>...]" for every drop-in this script wrote
gated_dropins() {
  local f unit paths
  for f in "$UNIT_DIR"/*.service.d/"$DROPIN"; do
    [ -f "$f" ] || continue
    grep -q "$MARKER" "$f" || continue
    unit=$(basename "$(dirname "$f")"); unit=${unit%.d}
    [ -z "${ONLY_UNIT:-}" ] || [ "$unit" = "$ONLY_UNIT" ] || continue   # selftest looks at its own unit only
    paths=$(sed -n 's/^ConditionPathIsMountPoint=//p' "$f" | sed "s|%h|$HOME|g" | tr '\n' ' ')
    printf '%s\t%s\n' "$unit" "${paths% }"
  done
}

all_mounted() { local p; for p in $1; do mountpoint -q "$p" || return 1; done; }

cmd_list() {
  local unit paths p state bound n=0
  while IFS=$'\t' read -r unit paths; do
    n=$((n + 1)); state=""
    for p in $paths; do if mountpoint -q "$p"; then state+="$p:up "; else state+="$p:DOWN "; fi; done
    printf '%-45s %s\n' "$unit" "$state"
  done < <(gated_dropins)
  if [ "$n" = 0 ]; then
    bound=$(bound_trees | tr '\n' ' ') || bound="unknown (see above)"
    say "no gated units (trees $FSTAB still binds under \$HOME: ${bound:-none})"
  fi
}

# the last journal line of a unit says "skipped, unmet condition check ConditionPathIsMountPoint=..." when its most
# recent start was skipped: nothing else records a skipped start (the unit just stays inactive, ConditionResult is
# "no" for never-started units too)
was_skipped_for_mount() {
  local last
  last=$(journalctl --user -b -u "$1" -n 1 -o cat --no-pager 2>/dev/null || true)
  case $last in *"unmet condition check ConditionPathIsMountPoint"*|*"condition failed"*) return 0 ;; esac
  return 1
}

# start the instances of unit $1 (a template name@.service covers every instance) that are inactive and whose last
# start was skipped for a mount condition; $2 is the reason shown. The same rules for `retry` and for `install` after it
# removed a gate: nothing else would start a unit whose start was skipped.
start_skipped() {
  local unit=$1 cand
  local -a cands=()
  if [[ $unit == *@.service ]]; then
    mapfile -t cands < <(systemctl --user list-units --all --plain --no-legend --type=service "${unit%@.service}@*.service" | awk '{print $1}')
  else
    cands=("$unit")
  fi
  for cand in "${cands[@]}"; do
    [ -n "$cand" ] || continue
    [ "$(systemctl --user show -p ActiveState --value "$cand" 2>/dev/null)" = inactive ] || continue
    # supervised on-demand workers keep their gate (never run in an empty tree) but are never started here: their
    # supervisor (3d-printer-ondemand@) retries a skipped start itself, and a retry-start would leave an idle worker running
    [[ " $NO_RETRY_START " == *" $unit "* ]] && continue
    # a timer-driven unit runs again on its next tick; starting it here would only duplicate a run
    [ -z "$(systemctl --user show -p TriggeredBy --value "$cand" 2>/dev/null)" ] || continue
    was_skipped_for_mount "$cand" || continue
    say "backups-user-gates: $2, starting $cand (its start was skipped for a mount condition)"
    do_it systemctl --user start --no-block "$cand" || say "  could not start $cand (masked or refusing manual starts?), the others are still tried"
  done
}

cmd_retry() {
  local unit paths p
  local -A seen_tree=()
  while IFS=$'\t' read -r unit paths; do
    for p in $paths; do seen_tree[$p]=1; done
    all_mounted "$paths" || continue
    start_skipped "$unit" "mounts are back"
  done < <(gated_dropins)
  # the selftest must not start real workloads or burn container retry attempts
  [ -n "${ONLY_UNIT:-}" ] || retry_docker_containers "${!seen_tree[@]}"
}

# docker: containers with a restart policy whose start failed (a bind source in a gated tree was missing or
# unwritable) are not retried by the daemon after a late plug-in. A container is started only when EVERY gated tree
# it binds from is mounted (starting it earlier would only fail again), at most 3 times per boot (the list lives in
# the runtime dir) so one that keeps failing for another reason is not restarted every two minutes.
# every docker call is bounded: a stalled daemon must not hang the retry run
docker() { timeout 8 /usr/bin/env docker "$@"; }

retry_docker_containers() {
  [ "$#" -gt 0 ] || return 0   # no gated tree (every tree is a plain directory again): no container can be waiting for one
  [ -n "$(type -P docker)" ] || return 0
  local tried_file="$STATE_DIR/backups-user-gates.docker-tried"
  local id policy err line src t attempts ready
  local -a needed
  local deadline=$((SECONDS + 200))   # ends the pass well inside the service's 5 min TimeoutStartSec
  while read -r id; do
    [ -n "$id" ] || continue
    # cheap checks first: a spent retry budget costs no docker call
    attempts=$(grep -cx "$id" "$tried_file" 2>/dev/null || true)
    [ "${attempts:-0}" -lt 3 ] || continue
    if [ "$SECONDS" -ge "$deadline" ]; then say "backups-user-gates: docker pass out of time, the rest is left to the next run"; break; fi
    policy=$(docker inspect -f '{{.HostConfig.RestartPolicy.Name}}' "$id" 2>/dev/null) || continue
    case $policy in always|unless-stopped|on-failure) ;; *) continue ;; esac
    err=$(docker inspect -f '{{.State.Error}}' "$id" 2>/dev/null) || continue
    [ -n "$err" ] || continue
    needed=(); ready=1
    # one bind source per line: HostConfig.Binds entries are "source:target[:options]", structured mounts carry Source
    while read -r line; do
      [ -n "$line" ] || continue
      src=${line%%:*}
      for t in "$@"; do
        case $src in "$t"|"$t"/*) needed+=("$t"); mountpoint -q "$t" || ready=0 ;; esac
      done
    done < <(docker inspect -f '{{range .HostConfig.Binds}}{{println .}}{{end}}{{range .HostConfig.Mounts}}{{if eq .Type "bind"}}{{println .Source}}{{end}}{{end}}' "$id" 2>/dev/null || true)
    [ "${#needed[@]}" -gt 0 ] && [ "$ready" = 1 ] || continue
    say "backups-user-gates: mounts are back, starting container $(docker inspect -f '{{.Name}}' "$id") (start failed: $err)"
    if [ "$DRY" = 0 ]; then printf '%s\n' "$id" >> "$tried_file"; docker start "$id" >/dev/null || true; else say "  [dry-run] docker start $id"; fi
  done < <(docker ps -a --filter status=exited --filter status=created -q 2>/dev/null || true)
}

# Proves on a throw-away fstab and unit dir (nothing real is read or written, no systemd call) that only trees with an
# ACTIVE bind line are gated: a commented-out line (what move-from-backups.sh leaves), a line without the bind option and
# a tree that is not in fstab at all give no gate; a HOME with a trailing slash and an fstab with no active line are
# handled (the latter is "unknown"); a stale gate of ours is removed, a drop-in without our marker is left alone; an
# unreadable fstab stops install before it changes anything; the retry timer follows the gate count. Runs inside
# cmd_selftest: `expect` and its failure flag live there.
selftest_fstab_filter() {
  local tmp unit="bgt-selftest-fstab.service" f bound out rc_bad install_rc
  tmp=$(mktemp -d)
  local UNIT_DIR="$tmp/units" FSTAB="$tmp/fstab"   # dynamic scope: sync_gate, bound_trees and cmd_install read these
  f="$UNIT_DIR/$unit.d/$DROPIN"
  mkdir -p "$UNIT_DIR/$unit.d"
  printf '%s\n' \
    "UUID=1111 / ext4 defaults 0 1" \
    "UUID=0000 /run/media/test/backups ext4 defaults,nofail 0 2" \
    "/run/media/test/backups/home/xp $HOME/xp none bind,nofail 0 0" \
    "# [move-from-backups 20261111-025654] /run/media/test/backups/home/work $HOME/work none bind,nofail 0 0" \
    "/run/media/test/backups/home/.npm $HOME/.npm none nofail 0 0" \
    "/run/media/test/backups/home/trail $HOME/trail/ none bind,nofail 0 0" \
    "/run/media/test/backups/home/dbl $HOME//dbl none bind,nofail 0 0" \
    "/run/media/test/backups/home/sp\\040ace $HOME/sp\\040ace none bind,nofail 0 0" > "$FSTAB"
  bound=$(bound_trees)
  expect "fstab: only active bind lines count (\\040 decoded, trailing and doubled slashes dropped)" "xp|trail|dbl|sp ace" "$(paste -sd'|' <<< "$bound")"
  expect "fstab: a HOME with a trailing slash finds the same trees" "xp|trail|dbl|sp ace" "$(HOME="$HOME/" bound_trees | paste -sd'|')"
  expect "fstab: commented, non-bind and unknown trees are not gated" xp "$(active_trees "xp work .npm nosuch" "$bound")"
  printf '# only comments\n' > "$tmp/empty"; rc_bad=0; FSTAB="$tmp/empty" bound_trees >/dev/null 2>&1 || rc_bad=$?
  expect "fstab: a file without any active line is rejected as unknown" rejected "$([ "$rc_bad" != 0 ] && echo rejected || echo accepted)"
  GATED=0; UNGATED=()
  sync_gate "$unit" "work .npm" "$bound" >/dev/null
  expect "no gate is written when no tree of the unit is bound, the unit is listed as ungated" "0 absent $unit" "$GATED $([ -e "$f" ] || echo absent) ${UNGATED[*]}"
  printf '# %s selftest\n[Unit]\nConditionPathIsMountPoint=%%h/work\n' "$MARKER" > "$f"
  sync_gate "$unit" "work" "$bound" >/dev/null
  expect "a stale gate of ours is removed with its empty .d dir" absent "$([ -e "$UNIT_DIR/$unit.d" ] && echo present || echo absent)"
  mkdir -p "$UNIT_DIR/$unit.d"; printf '[Unit]\nConditionPathExists=/tmp\n' > "$f"
  GATED=0; UNGATED=()
  sync_gate "$unit" "work" "$bound" >/dev/null
  expect "a drop-in without our marker is left alone" "ConditionPathExists=/tmp" "$(sed -n 2p "$f")"
  rm -f "$f"
  sync_gate "$unit" "xp work" "$bound" >/dev/null
  expect "a gate is written for the bound tree only" "1 ConditionPathIsMountPoint=%h/xp" "$GATED $(grep -h '^Condition' "$f" | paste -sd' ')"
  install_rc=0; out=$(DRY=1 FSTAB="$tmp/missing" cmd_install 2>&1) || install_rc=$?
  expect "an unreadable fstab aborts install before it changes anything" "aborted" \
    "$([ "$install_rc" != 0 ] && [[ $out == *"cannot read"* && $out != *"== retry helper"* ]] && echo aborted || echo "rc=$install_rc: $out")"
  out=$(DRY=1 sync_retry_timer 0)
  expect "no gated unit: the retry timer is disabled" yes "$([[ $out == *"disable --now backups-mount-retry.timer"* ]] && echo yes || echo no)"
  out=$(DRY=1 sync_retry_timer 2)
  expect "gated units: the retry timer is enabled" yes "$([[ $out == *"enable --now backups-mount-retry.timer"* ]] && echo yes || echo no)"
  rm -rf "$tmp"
}

# Exercises the whole skip -> retry loop on a throw-away unit without touching any real mount: the drop-in first
# points at a path that is not a mount point (the start is skipped), then at /dev/shm, which always is one (what
# "the disk came back" looks like to the unit); `retry` (restricted to that unit, docker recovery off) must leave it
# alone in the first state and start it in the second. The unit has a name unique to this run and is removed again,
# also on failure. It changes real systemd state, so there is no --dry-run. The fstab filter checks run first.
cmd_selftest() {
  [ "$DRY" = 0 ] || { echo "selftest starts and stops a real throw-away unit: no --dry-run" >&2; return 2; }
  local unit="bgt-selftest-$$.service" rc=0
  local dir="$UNIT_DIR/$unit.d"
  ONLY_UNIT=$unit
  state() { systemctl --user is-active "$unit" || true; }
  expect() { if [ "$2" = "$3" ]; then say "  ok    $1"; else say "  FAIL  $1 (got '$3', want '$2')"; rc=1; fi; }
  selftest_fstab_filter
  cleanup_selftest() { # $1 unit, $2 drop-in dir, $3 unit file; also runs from the EXIT trap, after this function's locals are gone
    systemctl --user stop "$1" 2>/dev/null || true
    rm -f "$2/$DROPIN" "$3"; rmdir "$2" 2>/dev/null || true
    systemctl --user daemon-reload
  }
  # shellcheck disable=SC2064  # expand now: the variables are locals of this function
  trap "cleanup_selftest '$unit' '$dir' '$UNIT_DIR/$unit'" EXIT
  mkdir -p "$dir"
  printf '[Unit]\nDescription=backups-user-gates selftest\n[Service]\nExecStart=/bin/sleep 120\n' > "$UNIT_DIR/$unit"
  printf '# %s selftest\n[Unit]\nConditionPathIsMountPoint=/nonexistent-selftest-mountpoint\n' "$MARKER" > "$dir/$DROPIN"
  systemctl --user daemon-reload
  systemctl --user start "$unit"
  expect "start skipped while the mount is missing" inactive "$(state)"
  local skipped=no; was_skipped_for_mount "$unit" && skipped=yes
  expect "journal records the skipped start" yes "$skipped"
  cmd_retry >/dev/null
  expect "retry leaves it alone while the mount is still missing" inactive "$(state)"
  printf '# %s selftest\n[Unit]\nConditionPathIsMountPoint=/dev/shm\n' "$MARKER" > "$dir/$DROPIN"
  systemctl --user daemon-reload
  cmd_retry >/dev/null
  sleep 1
  expect "retry starts it once the mount is back" active "$(state)"
  # a gate that install removes (its tree is not bound any more) must not leave the unit it had skipped stopped; a second
  # run (no gate file left to remove) must still start it, so that an interrupted install is finished by the next one
  systemctl --user stop "$unit"
  printf '# %s selftest\n[Unit]\nConditionPathIsMountPoint=/nonexistent-selftest-mountpoint\n' "$MARKER" > "$dir/$DROPIN"
  systemctl --user daemon-reload
  systemctl --user start "$unit"
  expect "stale gate: the start is skipped" inactive "$(state)"
  UNGATED=()
  sync_gate "$unit" "xp" "" >/dev/null
  UNGATED=()
  sync_gate "$unit" "xp" "" >/dev/null
  systemctl --user daemon-reload
  start_skipped "${UNGATED[0]:-none}" "selftest: no gate any more" >/dev/null
  sleep 1
  expect "install starts the unit that the removed gate had skipped" active "$(state)"
  cleanup_selftest "$unit" "$dir" "$UNIT_DIR/$unit"; trap - EXIT
  return $rc
}

cmd=${1:-}; shift || true
for a in "$@"; do case $a in --dry-run) DRY=1 ;; *) echo "unknown option: $a" >&2; exit 2 ;; esac; done
case $cmd in
  install) cmd_install ;;
  revert) cmd_revert ;;
  retry) cmd_retry ;;
  list) cmd_list ;;
  selftest) cmd_selftest ;;
  *) awk 'NR > 1 && !/^#/ {exit} NR > 1' "$0"; exit 2 ;;
esac
